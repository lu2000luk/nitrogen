<script lang="ts">
	let serverUrl = "https://nitrofs.lu2000luk.com";

	type Download = {
		url: string;
		progress: number;
		id?: string;
		completed?: boolean;
		mode?: "mp3" | "mp4";
	};

	let downloads: Download[] = $state([]);

	let isLoading = $state(false);
	let mode = $state(true); // true = video, false = audio only

	let inputUrl = $state("");

	async function download() {
		if (
			!inputUrl ||
			!serverUrl ||
			!inputUrl.startsWith("http") ||
			inputUrl.length < 8
		)
			return;
		if (isLoading) return;
		isLoading = true;

		let encoded = encodeURIComponent(btoa(inputUrl));
		let encoded_mode = mode ? "4" : "3";

		try {
			let res = await fetch(
				`${serverUrl}/download?u=${encoded}&m=${encoded_mode}`
			);

			let rid = "";

			if (!res.ok) throw new Error(`HTTP error! Status: ${res.status}`);
			const decoder = new TextDecoder("utf-8");

			// @ts-ignore
			for await (const chunk of res.body) {
				const text = decoder.decode(chunk, { stream: true });
				console.log(text);

				if (text.startsWith("PROGRESS|")) {
					const [_, progress] = text.trim().split("|");
					const index = downloads.findIndex((d) => d.id === rid);
					if (index !== -1) {
						downloads[index].progress = parseFloat(progress);
						downloads = [...downloads];
					}

					console.log(`Progress update: ${progress}%`);
				} else if (text.startsWith("ID|")) {
					const [_, id] = text.trim().split("\n")[0].split("|");
					downloads = [...downloads, { url: inputUrl, progress: 0, id, mode: mode ? "mp4" : "mp3" }];
					rid = id;
					console.log("Download started:", id);
				} else if (text.startsWith("ERROR|")) {
					const [_, message] = text.trim().split("|");
					alert(`Download error: ${message}`);
					isLoading = false;
					inputUrl = "";
					return;
				} else if (text.startsWith("SUCCESS|")) {
					const index = downloads.findIndex((d) => d.id === rid);
					if (index !== -1) {
						downloads[index].completed = true;
						downloads = [...downloads];
					}

					console.log("Download completed:", rid);
				}
			}
		} catch (err) {
			alert("Failed to start download");
			console.error(err);
		} finally {
			isLoading = false;
			inputUrl = "";
		}
	}

	function resolve(id: string, mode: "mp3" | "mp4" = "mp4") {
		window.open(`${serverUrl}/resolve?id=${id}&ext=${mode}`, "_blank");
	}
</script>

